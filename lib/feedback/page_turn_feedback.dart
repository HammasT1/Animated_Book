import 'package:audioplayers/audioplayers.dart';
import 'package:flutter/foundation.dart';
import 'package:flutter/services.dart';
import 'package:flutter/widgets.dart';

/// What the reader hears and feels when a page turns.
///
/// The reader decides *whether* (from the reader's settings) and calls
/// [turnStarted] as a page starts to turn and [turnLanded] when it settles.
/// This base class does nothing, which is what tests and the silent default
/// use.
class PageTurnFeedback {
  const PageTurnFeedback();

  /// A page has started turning: the paper sound.
  void turnStarted() {}

  /// The page has landed: a light tap on devices that vibrate.
  void turnLanded() {}

  void dispose() {}
}

/// Plays one of the bundled page-turn sounds (generated by
/// `tool/generate_page_sounds.py`) and a light haptic tap.
///
/// Sound respects the phone's silent mode and mixes with any music already
/// playing instead of interrupting it. If audio can't be set up on this
/// device, turns simply stay silent.
class DevicePageTurnFeedback extends PageTurnFeedback {
  DevicePageTurnFeedback({this.volume = 0.6});

  final double volume;

  static const List<String> _sounds = [
    'sounds/page_turn_1.wav',
    'sounds/page_turn_2.wav',
    'sounds/page_turn_3.wav',
  ];

  /// One player per variation, so a quick second turn doesn't cut the
  /// first one off.
  List<AudioPlayer>? _players;
  int _next = 0;
  bool _audioFailed = false;

  List<AudioPlayer> _ensurePlayers() {
    final existing = _players;
    if (existing != null) return existing;
    try {
      AudioPlayer.global
          .setAudioContext(
            AudioContextConfig(
              focus: AudioContextConfigFocus.mixWithOthers,
              respectSilence: true,
            ).build(),
          )
          .catchError((Object e) => debugPrint('Audio context: $e'));
    } catch (e) {
      debugPrint('Audio context: $e');
    }
    return _players = [
      for (var i = 0; i < _sounds.length; i++)
        AudioPlayer()..setReleaseMode(ReleaseMode.stop),
    ];
  }

  @override
  void turnStarted() {
    if (_audioFailed) return;
    try {
      final players = _ensurePlayers();
      // Cycle through the variations so repeated turns sound natural.
      final i = _next;
      _next = (_next + 1) % players.length;
      players[i]
          .play(
            AssetSource(_sounds[i]),
            volume: volume,
            // Android's SoundPool starts short sounds with the least delay.
            mode: !kIsWeb && defaultTargetPlatform == TargetPlatform.android
                ? PlayerMode.lowLatency
                : PlayerMode.mediaPlayer,
          )
          .catchError(_disableAudio);
    } catch (e) {
      _disableAudio(e);
    }
  }

  void _disableAudio(Object error) {
    if (_audioFailed) return;
    _audioFailed = true;
    debugPrint('Page-turn sound disabled: $error');
  }

  @override
  void turnLanded() {
    HapticFeedback.lightImpact();
  }

  @override
  void dispose() {
    for (final player in _players ?? const <AudioPlayer>[]) {
      player.dispose();
    }
    _players = null;
  }
}

/// Makes the app's [PageTurnFeedback] available to the reader.
class PageTurnFeedbackScope extends InheritedWidget {
  const PageTurnFeedbackScope({
    super.key,
    required this.feedback,
    required super.child,
  });

  final PageTurnFeedback feedback;

  /// The feedback above [context], or a silent one if there is none.
  static PageTurnFeedback of(BuildContext context) =>
      context
          .getInheritedWidgetOfExactType<PageTurnFeedbackScope>()
          ?.feedback ??
      const PageTurnFeedback();

  @override
  bool updateShouldNotify(PageTurnFeedbackScope oldWidget) =>
      feedback != oldWidget.feedback;
}
